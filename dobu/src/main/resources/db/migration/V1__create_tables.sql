CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(255) NOT NULL,
                         email VARCHAR(255) UNIQUE,
                         senha VARCHAR(255) NOT NULL,
                         tipo_usuario VARCHAR(50)
);

CREATE TABLE especie (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(255),
                         descricao VARCHAR(1000)
);

CREATE TABLE raca (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      nome VARCHAR(255),
                      porte VARCHAR(100),
                      expectativa_vida INTEGER,
                      descricao VARCHAR(1000),
                      cuidados VARCHAR(1000),
                      id_especie BIGINT,
                      CONSTRAINT fk_raca_especie
                          FOREIGN KEY (id_especie)
                              REFERENCES especie(id)
);

CREATE TABLE pet (
                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                     nome VARCHAR(255),
                     idade INTEGER,
                     id_raca BIGINT,
                     id_tutor BIGINT,
                     CONSTRAINT fk_pet_raca
                         FOREIGN KEY (id_raca)
                             REFERENCES raca(id),
                     CONSTRAINT fk_pet_tutor
                         FOREIGN KEY (id_tutor)
                             REFERENCES usuario(id)
);

CREATE TABLE consulta (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          data_consulta TIMESTAMP,
                          descricao VARCHAR(1000),
                          valor DOUBLE,
                          id_pet BIGINT,
                          id_veterinario BIGINT,
                          CONSTRAINT fk_consulta_pet
                              FOREIGN KEY (id_pet)
                                  REFERENCES pet(id),
                          CONSTRAINT fk_consulta_veterinario
                              FOREIGN KEY (id_veterinario)
                                  REFERENCES usuario(id)
);

CREATE TABLE agendamento (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             data_agendamento TIMESTAMP,
                             status VARCHAR(100),
                             id_pet BIGINT,
                             id_veterinario BIGINT,
                             CONSTRAINT fk_agendamento_pet
                                 FOREIGN KEY (id_pet)
                                     REFERENCES pet(id),
                             CONSTRAINT fk_agendamento_veterinario
                                 FOREIGN KEY (id_veterinario)
                                     REFERENCES usuario(id)
);

CREATE TABLE historico_sistema (
                                   id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                   tipo_evento VARCHAR(255),
                                   nome_procedure VARCHAR(255),
                                   usuario_banco VARCHAR(255),
                                   data_ocorrencia TIMESTAMP,
                                   descricao VARCHAR(1000)
);

CREATE TABLE pagamento (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           valor DOUBLE,
                           forma_pagamento VARCHAR(100),
                           data_pagamento DATE,
                           id_consulta BIGINT UNIQUE,
                           CONSTRAINT fk_pagamento_consulta
                               FOREIGN KEY (id_consulta)
                                   REFERENCES consulta(id)
);

CREATE TABLE prontuario (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            diagnostico VARCHAR(1000),
                            observacoes VARCHAR(2000),
                            id_consulta BIGINT UNIQUE,
                            CONSTRAINT fk_prontuario_consulta
                                FOREIGN KEY (id_consulta)
                                    REFERENCES consulta(id)
);

CREATE TABLE vacina (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        nome_vacina VARCHAR(255),
                        data_aplicacao DATE,
                        proxima_dose DATE,
                        id_pet BIGINT,
                        CONSTRAINT fk_vacina_pet
                            FOREIGN KEY (id_pet)
                                REFERENCES pet(id)
);