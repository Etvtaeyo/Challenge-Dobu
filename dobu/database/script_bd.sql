CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    senha VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(50) NOT NULL
);
COMMENT ON TABLE usuario IS 'Usuários do sistema: donos e veterinários';

CREATE TABLE IF NOT EXISTS especie (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    descricao VARCHAR(1000)
);
COMMENT ON TABLE especie IS 'Espécies dos animais atendidos pela clínica';

CREATE TABLE IF NOT EXISTS raca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    porte VARCHAR(100),
    expectativa_vida INTEGER,
    descricao VARCHAR(1000),
    cuidados VARCHAR(1000),
    id_especie BIGINT NOT NULL REFERENCES especie(id)
);
COMMENT ON TABLE raca IS 'Raças relacionadas às espécies';

CREATE TABLE IF NOT EXISTS pet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255) NOT NULL,
    idade INTEGER NOT NULL,
    id_raca BIGINT NOT NULL REFERENCES raca(id),
    id_dono BIGINT NOT NULL REFERENCES usuario(id)
);
COMMENT ON TABLE pet IS 'Pets cadastrados na clínica';

CREATE TABLE IF NOT EXISTS consulta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_consulta TIMESTAMP NOT NULL,
    descricao VARCHAR(1000) NOT NULL,
    valor NUMERIC(10,2) NOT NULL,
    id_pet BIGINT NOT NULL REFERENCES pet(id),
    id_veterinario BIGINT NOT NULL REFERENCES usuario(id)
);
COMMENT ON TABLE consulta IS 'Consultas veterinárias realizadas ou agendadas';

CREATE TABLE IF NOT EXISTS agendamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_agendamento TIMESTAMP NOT NULL,
    status VARCHAR(100) NOT NULL,
    id_pet BIGINT NOT NULL REFERENCES pet(id),
    id_veterinario BIGINT NOT NULL REFERENCES usuario(id)
);

CREATE TABLE IF NOT EXISTS vacina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_vacina VARCHAR(255) NOT NULL,
    data_aplicacao DATE NOT NULL,
    proxima_dose DATE NOT NULL,
    id_pet BIGINT NOT NULL REFERENCES pet(id)
);

CREATE TABLE IF NOT EXISTS pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    valor NUMERIC(10,2) NOT NULL,
    forma_pagamento VARCHAR(100) NOT NULL,
    data_pagamento DATE NOT NULL,
    id_consulta BIGINT UNIQUE NOT NULL REFERENCES consulta(id)
);

CREATE TABLE IF NOT EXISTS prontuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnostico VARCHAR(1000) NOT NULL,
    observacoes VARCHAR(2000),
    id_consulta BIGINT UNIQUE NOT NULL REFERENCES consulta(id)
);

